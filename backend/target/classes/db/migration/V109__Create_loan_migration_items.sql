CREATE TABLE IF NOT EXISTS loan_migration_items (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    row_number INT NOT NULL,
    employee_id VARCHAR(50) NOT NULL,
    loan_product_name VARCHAR(100) NOT NULL,
    principal_amount DECIMAL(15,2) NOT NULL,
    term_months INT NOT NULL,
    interest_rate DECIMAL(5,2),
    disbursement_date DATE NOT NULL,
    loan_status VARCHAR(20) NOT NULL,
    outstanding_balance DECIMAL(15,2) NOT NULL,
    guarantorship_type VARCHAR(10) NOT NULL,
    purpose VARCHAR(500),
    guarantor1_employee_id VARCHAR(50),
    guarantor1_pledge_amount DECIMAL(15,2),
    guarantor2_employee_id VARCHAR(50),
    guarantor2_pledge_amount DECIMAL(15,2),
    guarantor3_employee_id VARCHAR(50),
    guarantor3_pledge_amount DECIMAL(15,2),
    guarantor4_employee_id VARCHAR(50),
    guarantor4_pledge_amount DECIMAL(15,2),
    guarantor5_employee_id VARCHAR(50),
    guarantor5_pledge_amount DECIMAL(15,2),
    guarantor6_employee_id VARCHAR(50),
    guarantor6_pledge_amount DECIMAL(15,2),
    total_interest DECIMAL(15,2),
    total_repayable DECIMAL(15,2),
    monthly_repayment DECIMAL(15,2),
    loan_id BIGINT,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    error_message VARCHAR(1000),
    processed_at DATETIME,
    FOREIGN KEY (batch_id) REFERENCES bulk_batches(id),
    FOREIGN KEY (loan_id) REFERENCES loans(id)
);
